#pragma once

#include "DxLib.h"
#include "MeshCut.h"

#include <vector>

class MeshCutter
{
public:

    // ============================================================
    // 切断された破片
    // ============================================================

    struct Piece
    {
        MeshCut::Mesh mesh;

        VECTOR pos;
        VECTOR vel;

        int color;
    };

public:

    // ============================================================
    // メッシュを設定
    // ============================================================

    void SetMesh(
        const MeshCut::Mesh& mesh);


    // ============================================================
    // 元の状態に戻す
    // ============================================================

    void Reset();


    // ============================================================
    // 切断
    //
    // origin : 切断平面上の点
    // normal : 切断平面の法線
    // ============================================================

    void Cut(
        VECTOR origin,
        VECTOR normal);


    // ============================================================
    // 押し出し速度を指定して切断
    // ============================================================

    void Cut(
        VECTOR origin,
        VECTOR normal,
        float pushSpeed);


    // ============================================================
    // 更新
    // ============================================================

    void Update(
        float damping = 0.92f);


    // ============================================================
    // 描画
    // ============================================================

    void Draw();


    // ============================================================
    // 破片数
    // ============================================================

    int GetPieceCount() const;


    // ============================================================
    // 破片取得
    // ============================================================

    const std::vector<Piece>&
        GetPieces() const;


    std::vector<Piece>&
        GetPieces();


    // ============================================================
    // 押し出し速度設定
    // ============================================================

    void SetPushSpeed(
        float speed);


private:

    // 元のメッシュ
    MeshCut::Mesh originalMesh_;

    // 現在の破片
    std::vector<Piece> pieces_;

    // 色番号
    int colorCounter_ = 0;

    // 切断時の押し出し速度
    float pushSpeed_ = 1.0f;


    // ============================================================
    // 破片カラー
    // ============================================================

    static constexpr int Palette[6][3] =
    {
        {230, 110, 90},
        { 90, 150, 230},
        {110, 200, 120},
        {230, 190,  80},
        {190, 110, 220},
        { 90, 200, 200}
    };

    // ============================================================
    // 破片1個を描画
    // ============================================================

    void DrawPiece(
        const Piece& piece,
        VECTOR light);
};